import { expect, test } from "@playwright/test";
import { mkdtempSync, realpathSync, rmSync, writeFileSync, renameSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { buildSync } from "esbuild";
import { apiDelete, apiPatch, apiPost, base, expandFolder } from "./helpers";

test("top-level readers filter artifacts, run bundled React, and retain versioned file feedback", async ({ page }) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1600, height: 1000 });
  const root = realpathSync(mkdtempSync(join(tmpdir(), "artifact-nav-")));
  const moved = root + "-moved";
  const launched = await apiPost("/sessions/launch", { command: "python3 -u -c 'import sys; print(\"READY\"); [print(\"RECEIVED \"+line) for line in sys.stdin]'", cwd: root, runtime: "generic", name: "Reader review", in_terminal: false, test: true });
  expect(launched.status).toBe(200);
  const key = String(launched.body.session_key);
  try {
    await apiPatch(`/sessions/${key}`, { group: "Reader tests" });
    const enrollment = await apiPost(`/sessions/${key}/collaboration`, { root: "Reader tests" });
    const register = async (name: string, title: string, kind: string, text: string) => {
      const response = await fetch(`${base()}/api/v1/session/artifacts`, { method: "POST", headers: { Authorization: `Bearer ${enrollment.body.token}`, "Content-Type": "application/json" }, body: JSON.stringify({ source_path: join(root, name), title, kind, content_base64: Buffer.from(text).toString("base64") }) });
      expect(response.status).toBe(200);
    };
    const script = buildSync({ stdin: { contents: `import React from 'react'; import {createRoot} from 'react-dom/client'; function App(){const[n,set]=React.useState(0);return <main><h1>Release dashboard</h1><p>Ready for review</p><button onClick={()=>set(n+1)}>Checked {n}</button></main>} createRoot(document.getElementById('app')).render(<App/>);`, loader: "jsx", resolveDir: process.cwd() }, bundle: true, write: false, minify: true, define: { "process.env.NODE_ENV": '"production"' } }).outputFiles[0].text;
    const doc = `<div id="app"></div><script>${script.replaceAll("</script", "<\\/script")}</script><script>fetch('/blocked-resource').catch(()=>{});try{parent.document.body.dataset.escaped='yes'}catch(e){document.body.dataset.isolated='yes'}</script>`;
    await register("release.react.html", "Release dashboard", "preview", doc);
    await register("decision.md", "Release decision", "kdd", "# Release decision\n\nReview before shipping.");
    writeFileSync(join(root, "notes.txt"), "Current source for review");
    await page.goto(base());
    await expandFolder(page, "Reader tests");
    await page.locator(".rd-row-name", { hasText: "Reader review" }).click();
    const tabs = page.locator(".rd-view-toggle");
    const names = await tabs.locator("button").allTextContents();
    expect(names.indexOf("Code explorer")).toBe(names.findIndex(n => n.startsWith("Inbox")) + 1);
    expect(names.indexOf("Artifacts")).toBe(names.indexOf("Code explorer") + 1);
    await tabs.getByRole("button", { name: "Artifacts", exact: true }).click();
    await page.getByLabel("Artifact format", { exact: true }).selectOption("react");
    await expect(page.getByRole("button", { name: "Markdown Release decision" })).toHaveCount(0);
    await page.getByRole("button", { name: "React app Release dashboard" }).click();
    const frame = page.frameLocator('iframe[title="Preview of Release dashboard"]');
    await frame.getByRole("button", { name: "Checked 0" }).click();
    await expect(frame.getByRole("button", { name: "Checked 1" })).toBeVisible();
    expect(await page.locator("body").getAttribute("data-escaped")).toBeNull();
    await expect(frame.locator("body")).toHaveAttribute("data-isolated", "yes");
    await page.getByRole("button", { name: "Comments (0)", exact: true }).click();
    await expect(frame.getByRole("button", { name: "Checked 1" })).toBeVisible();
    await frame.getByRole("heading").evaluate(node => { const range=node.ownerDocument.createRange(); range.selectNodeContents(node); const s=node.ownerDocument.defaultView!.getSelection()!;s.removeAllRanges();s.addRange(range);node.dispatchEvent(new MouseEvent("mouseup",{bubbles:true})); });
    await expect(page.getByRole("dialog", { name: "Artifact feedback" }).locator("blockquote")).toHaveText("“Release dashboard”");
    await page.getByLabel("Feedback to agent").fill("Make the next step clearer");
    await page.getByRole("button", { name: "Send ⌘↵" }).click();
    await expect(page.getByRole("complementary", { name: "Comment history" })).toContainText("Make the next step clearer");
    await page.getByRole("button", { name: "Show quote" }).click();
    await expect(page.getByText("Quote selected in this version.")).toBeVisible();
    await page.screenshot({ path: "/tmp/artifact-navigation-react-comments.png" });
    await page.getByRole("button", { name: "Source", exact: true }).click();
    await expect(page.locator(".rd-artifact-text")).toContainText("createElement");
    await page.getByLabel("Artifact format", { exact: true }).selectOption("all");
    await page.getByLabel("Search artifacts").fill("decision");
    await expect(page.getByRole("button", { name: "React app Release dashboard" })).toHaveCount(0);
    await page.getByRole("button", { name: "Markdown Release decision" }).click();
    await page.getByLabel("Change artifact label").selectOption("report");
    await page.getByLabel("Search artifacts").fill("report");
    await expect(page.getByRole("button", { name: "Markdown Release decision" })).toBeVisible();
    await register("release.react.html", "Release dashboard", "preview", doc.replace("Ready for review", "Revised content"));
    await page.getByRole("button", { name: "Refresh", exact: true }).click();
    await page.getByRole("button", { name: "React app Release dashboard" }).click();
    await page.getByRole("button", { name: "Comments (1)" }).click();
    await page.getByText("Earlier versions (1)").click();
    await expect(page.getByRole("complementary", { name: "Comment history" })).toContainText("Make the next step clearer");
    await expect(page.getByRole("button", { name: "Show quote" })).toHaveCount(0);
    await tabs.getByRole("button", { name: "Code explorer", exact: true }).click();
    await page.getByRole("button", { name: /notes.txt/ }).click();
    await page.getByRole("button", { name: "Leave feedback" }).click();
    await page.getByLabel("Feedback to agent").fill("Clarify source");
    await page.getByRole("button", { name: "Send ⌘↵" }).click();
    await expect(page.getByRole("complementary", { name: "Comment history" })).toContainText("Clarify source");
    await page.getByRole("button", { name: "Leave feedback" }).click();
    await page.getByLabel("Feedback to agent").fill("Keep this draft");
    writeFileSync(join(root, "notes.txt"), "Changed source");
    await page.getByRole("button", { name: "Send ⌘↵" }).click();
    await expect(page.getByRole("alert")).toContainText("This file changed");
    await expect(page.getByLabel("Feedback to agent")).toHaveValue("Keep this draft");
    await page.getByRole("button", { name: "Cancel", exact: true }).click();
    await page.screenshot({ path: "/tmp/artifact-navigation-code-comments.png" });
    renameSync(root, moved);
    await tabs.getByRole("button", { name: "Artifacts", exact: true }).click();
    await page.getByRole("button", { name: "Markdown Release decision" }).click();
    await expect(page.frameLocator('iframe[title="Preview of Release decision"]').getByRole("heading")).toHaveText("Release decision");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: "/tmp/artifact-navigation-mobile.png" });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally { await apiPost(`/sessions/${key}/stop`); await apiDelete(`/sessions/${key}`); rmSync(root, { recursive: true, force: true }); rmSync(moved, { recursive: true, force: true }); }
});
